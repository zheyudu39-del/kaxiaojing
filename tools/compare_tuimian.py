# 中文引号/破折号/括号/罗马数字等统一化，便于模糊匹配
_PUNCT = {
    "“": '"', "”": '"', "‘": "'", "’": "'",
    "（": "(", "）": ")", "〔": "(", "〕": ")",
    "—": "-", "－": "-", "–": "-", "─": "-",
    "·": "", "•": "", "．": ".", "。": "",
    "、": ",", "，": ",", "：": ":", "；": ";",
    "①": "", "②": "", "③": "", "④": "", "⑤": "", "⑥": "", "⑦": "", "⑧": "", "⑨": "", "⑩": "",
}


def norm(s: str) -> str:
    """归一化竞赛名，用于跨源匹配。"""
    s = str(s or "")
    for a, b in _PUNCT.items():
        s = s.replace(a, b)
    s = s.lower()
    s = re.sub(r"[\s\u200b\xa0]", "", s)          # 去所有空白（含原文多余空格）
    s = re.sub(r"^第[一二三四五六七八九十\d]+届", "", s)  # 去「第X届」前缀
    s = re.sub(r"^the", "", s)
    return s


def core(s: str) -> str:
    """
    取「核心名」——去掉多值子项与括号补充，用于更宽松的匹配。
    例：「全国大学生生命科学竞赛（CULSC）①生命科学竞赛、②生命创新创业大赛」
        → 「全国大学生生命科学竞赛」
    """
    s = str(s or "")
    # 去掉 -①... 或 ①... 之后的所有内容
    s = re.split(r"[-—]?\s*①", s)[0]
    # 去掉括号及其后内容
    s = re.split(r"[（(]", s)[0]
    return norm(s)


def main() -> int:
    api_file = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/comps.json")
    db = json.loads(api_file.read_text(encoding="utf-8"))
    db_comps = db.get("competitions", db)
    db_names = [c["name"] for c in db_comps]

    db_norm = {norm(n): n for n in db_names}
    db_core = {core(n): n for n in db_names}

    matched, missing = [], []
    for t in TUIMIAN:
        if norm(t) in db_norm or core(t) in db_core:
            matched.append((t, db_norm.get(norm(t)) or db_core.get(core(t))))
        else:
            missing.append(t)

    used_db = {v for _, v in matched}
    extra = [n for n in db_names if n not in used_db]

    print("=" * 70)
    print("  推免认定竞赛目录  ↔  项目竞赛库  比对")
    print("=" * 70)
    print(f"  推免目录：{len(TUIMIAN)} 条")
    print(f"  项目库  ：{len(db_names)} 条")
    print(f"  匹配上  ：{len(matched)} 条")
    print(f"  需新增  ：{len(missing)} 条")
    print(f"  库中额外：{len(extra)} 条")

    print("\n【需新增】推免目录有、项目库没有：")
    for i, n in enumerate(missing, 1):
        print(f"  {i:>2}. {n}")

    print("\n【库中额外】项目库有、推免目录没有：")
    for i, n in enumerate(extra, 1):
        print(f"  {i:>2}. {n}")

    print("\n【名称有差异但已匹配】")
    for t, d in matched:
        if t != d:
            print(f"  推免: {t}\n  库中: {d}\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
